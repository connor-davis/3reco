#!/usr/bin/env bash
# =============================================================================
#  3REco - one-command production deploy
#
#  Usage:
#    RESEND_API_KEY=... AUTH_FROM_EMAIL=... ./deploy.sh <domain>
#
#  What it does:
#    1. Derives the web origin from the domain
#    2. Makes the database, file store and field-encryption secrets if they
#       are not already in .env (existing ones are kept)
#    3. Writes .env
#    4. Builds and starts the stack: docker compose up -d --build
#
#  Prerequisites:
#    - Docker >= 24 with Compose v2
#    - A reverse proxy with HTTPS: app.<domain> -> 127.0.0.1:8180,
#      docs.<domain> -> 127.0.0.1:3001
# =============================================================================

set -euo pipefail

DOMAIN="${1:-}"

if [[ -z "$DOMAIN" ]]; then
  echo "Usage: $0 <domain>"
  echo "  e.g. RESEND_API_KEY=re_xxx AUTH_FROM_EMAIL=noreply@yourdomain.com $0 yourdomain.com"
  exit 1
fi

ENV_FILE=".env"

# Value of a key in .env, or empty.
existing() {
  [[ -f "$ENV_FILE" ]] || return 0
  grep -E "^$1=" "$ENV_FILE" 2>/dev/null | cut -d= -f2- | tr -d '"' || true
}

# Use the value from the environment, else the one already in .env, else make one.
pick() {
  local name="$1" make="$2" value="${!1:-}"
  [[ -n "$value" ]] || value="$(existing "$name")"
  if [[ -z "$value" && -n "$make" ]]; then
    value="$(eval "$make")"
    echo "Made a new $name" >&2
  fi
  printf '%s' "$value"
}

POSTGRES_PASSWORD="$(pick POSTGRES_PASSWORD 'openssl rand -hex 24')"
MINIO_ROOT_PASSWORD="$(pick MINIO_ROOT_PASSWORD 'openssl rand -hex 24')"
THREERECO_FIELD_KEY="$(pick THREERECO_FIELD_KEY 'openssl rand -base64 32')"
RESEND_API_KEY="$(pick RESEND_API_KEY '')"
AUTH_FROM_EMAIL="$(pick AUTH_FROM_EMAIL '')"
THREERECO_TRUSTED_PROXIES="$(pick THREERECO_TRUSTED_PROXIES '')"

if [[ -z "$RESEND_API_KEY" ]]; then
  echo "Warning: RESEND_API_KEY is not set. Sign-up and password reset emails will fail until you add it."
fi

if [[ -z "$AUTH_FROM_EMAIL" ]]; then
  AUTH_FROM_EMAIL="noreply@$DOMAIN"
fi

cat > "$ENV_FILE" <<EOT
# Generated by deploy.sh - do not commit this file
DOMAIN=$DOMAIN
THREERECO_WEB_ORIGIN=https://app.$DOMAIN
THREERECO_TRUSTED_PROXIES=$THREERECO_TRUSTED_PROXIES

POSTGRES_PASSWORD=$POSTGRES_PASSWORD
MINIO_ROOT_USER=threereco
MINIO_ROOT_PASSWORD=$MINIO_ROOT_PASSWORD

THREERECO_FIELD_KEY=$THREERECO_FIELD_KEY

RESEND_API_KEY=$RESEND_API_KEY
AUTH_FROM_EMAIL=$AUTH_FROM_EMAIL
EOT

echo "Written $ENV_FILE for domain: $DOMAIN"
echo "Back up THREERECO_FIELD_KEY away from the database backups: without it, ID and account numbers cannot be read."

docker compose up -d --build

echo ""
echo "Stack is up. The API and web app listen on 127.0.0.1:8180, docs on 127.0.0.1:3001."
echo "Point your proxy at them: https://app.$DOMAIN and https://docs.$DOMAIN"
echo "The API runs the database migrations by itself when it starts."
